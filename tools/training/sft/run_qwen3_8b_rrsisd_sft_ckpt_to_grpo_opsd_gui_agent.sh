timestamp="${RUN_TIMESTAMP:-$(date +%Y%m%d-%H%M%S)}"
sft_ckpt="${SFT_CKPT:-/mnt/jfs/copilot/lhb/checkpoint/rs/rs-sft/gui-sd-qwen3-8b-rrsisd_sft_e1_retry-20260529-094035/v0-20260529-094457/checkpoint-96}"

